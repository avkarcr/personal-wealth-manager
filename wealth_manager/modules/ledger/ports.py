from typing import Protocol

class LedgerRepository(Protocol):
    def enabled(self, account_id): ...
    def data(self): ...
    def activate(self, account_id, day, baseline): ...
    def register_position(self, holding_id): ...
    def find_request(self, request_id): ...
    def insert(self, entry): ...
    def void(self, entry_id, day): ...
    def update_balances(self, balances, realized): ...
    def link_flow(self, entry_id, flow_id): ...
    def remove_flows(self, entry_id): ...
    def invalidate_snapshots(self, entry_id, today): ...
    def owned_flow(self, flow_id): ...
    def get(self, entry_id): ...
