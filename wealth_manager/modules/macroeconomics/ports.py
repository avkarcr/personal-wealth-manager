from typing import Protocol, Sequence
from .domain import Observation

class ObservationRepository(Protocol):
    def save(self, record: Observation) -> int: ...
    def delete(self, record_id: int) -> None: ...

class Reader(Protocol):
    def read(self) -> Sequence[dict]: ...


class DataRepository(Protocol):
    def ingest(self,indicator,source,series,artifact,points) -> Sequence[int]: ...

class RevisionReader(Protocol):
    def read(self) -> Sequence[dict]: ...


class MacroProvider(Protocol):
    def fetch(self,kind,start,end) -> Sequence[tuple]: ...

class RefreshSession(Protocol):
    def check(self,token) -> None: ...
    def write(self,token): ...
