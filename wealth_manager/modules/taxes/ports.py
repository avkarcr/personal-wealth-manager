from typing import Protocol
from .domain import TaxEntry, Deduction

class TaxRepository(Protocol):
    def save_entry(self, record: TaxEntry) -> int: ...
    def save_deduction(self, record: Deduction) -> int: ...
    def delete_entry(self, record_id: int) -> None: ...
    def delete_deduction(self, record_id: int) -> None: ...

class Reader(Protocol):
    def read(self) -> dict: ...
