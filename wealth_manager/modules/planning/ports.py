from typing import Protocol
from .domain import Goal, Portfolio

class PlanningRepository(Protocol):
    def goal(self,record_id: int) -> dict: ...
    def portfolio(self,record_id: int) -> dict: ...
    def save_goal(self,goal: Goal) -> int: ...
    def delete_goal(self,record_id: int) -> None: ...
    def save_portfolio(self,portfolio: Portfolio) -> int: ...
    def delete_portfolio(self,record_id: int) -> None: ...
    def source(self,kind: str,record_id: int) -> dict: ...
    def assigned(self,kind: str,record_id: int,excluding_portfolio: int) -> int: ...
    def allocate(self,portfolio_id: int,kind: str,record_id: int,share_bps: int) -> None: ...
    def remove_allocation(self,portfolio_id: int,record_id: int) -> None: ...

class PlanningReader(Protocol):
    def read(self) -> dict: ...
