from typing import Protocol
from .domain import TaxEntry, Deduction

class TaxRepository(Protocol):
    def save_entry(self, record: TaxEntry) -> int: ...
    def save_deduction(self, record: Deduction) -> int: ...
    def delete_entry(self, record_id: int) -> None: ...
    def delete_deduction(self, record_id: int) -> None: ...

class Reader(Protocol):
    def read(self) -> dict: ...

class EvidenceRepository(Protocol):
    def entry(self,rid): ...
    def deduction(self,rid): ...
    def payments(self,rid): ...
    def payment(self,rid): ...
    def find_payment(self,key): ...
    def add_payment(self,payment): ...
    def void_payment(self,pid): ...
    def documents(self,entry_id=None,deduction_id=None): ...
    def document(self,did): ...
    def size(self): ...
    def add_document(self,document): ...
    def delete_document(self,did): ...
