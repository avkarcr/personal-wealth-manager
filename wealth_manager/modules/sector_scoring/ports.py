"""Outbound ports for encrypted snapshots and atomic writes."""
from typing import Protocol, ContextManager
from wealth_manager.modules.economic_cycle.ports import Repository as CycleRepository, Revisions


class Repository(Protocol):
    def state(self) -> dict: ...
    def sectors(self) -> list: ...
    def observations(self) -> list: ...
    def revision_token(self) -> int: ...
    def configure(self, config: dict, created: str) -> int: ...
    def observe(self, payload: dict, received: str) -> int: ...
    def save(self, fingerprint: str, result: dict, created: str) -> int: ...


class UnitOfWork(Protocol):
    sector_scoring: Repository
    economic_cycle: CycleRepository
    macro_data: Revisions
    def commit(self) -> None: ...


class Session(Protocol):
    def sector_snapshot(self, token: str) -> dict: ...
    def saved_sector(self, token: str, rid: int) -> dict: ...
    def write(self, token: str) -> ContextManager[UnitOfWork]: ...
