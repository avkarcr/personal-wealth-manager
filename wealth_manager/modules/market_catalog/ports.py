from typing import Protocol
from .domain import Sector, Security, Listing

class Repository(Protocol):
    def read(self) -> dict: ...
    def save_sector(self, record: Sector) -> int: ...
    def delete_sector(self, rid: int) -> None: ...
    def assign_sector(self, company_id: int, sector_id: int, primary: bool, source: str, as_of: str) -> None: ...
    def remove_sector(self, company_id: int, sector_id: int) -> None: ...
    def save_security(self, record: Security) -> int: ...
    def delete_security(self, rid: int) -> None: ...
    def save_listing(self, record: Listing) -> int: ...
    def delete_listing(self, rid: int) -> None: ...

class Reader(Protocol):
    def read(self) -> dict: ...
