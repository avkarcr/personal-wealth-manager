from typing import Protocol, Sequence
from .domain import Observation

class ObservationRepository(Protocol):
    def save(self, record: Observation) -> int: ...
    def delete(self, record_id: int) -> None: ...

class Reader(Protocol):
    def read(self) -> Sequence[dict]: ...


class DataRepository(Protocol):
    def refresh_state(self) -> dict: ...
    def save_refresh_state(self,state) -> None: ...
    def revision_token(self) -> int: ...
    def ingest(self,indicator,source,series,artifact,points) -> Sequence[int]: ...

class RevisionReader(Protocol):
    def read(self) -> Sequence[dict]: ...


class MacroProvider(Protocol):
    def fetch(self,kind,start,end) -> Sequence[tuple]: ...

class RefreshSession(Protocol):
    def current(self): ...
    def read_state(self,token) -> dict: ...
    def check(self,token) -> None: ...
    def write(self,token): ...


class StatisticalFileReader(Protocol):
    def evidence(self,file,config): ...
    def inspect(self,file) -> dict: ...
    def extract(self,file,config,frequency) -> tuple: ...


class ScheduledMacroProvider(Protocol):
    def fetch(self,kind,start,end,cancel) -> Sequence[tuple]: ...


class CalculationSession(Protocol):
    def calculation_snapshot(self,token) -> dict: ...
    def saved_calculation(self,token,rid) -> dict: ...
    def write(self,token): ...

class CalculationRepository(Protocol):
    def save(self,fingerprint,result,created) -> int: ...
    def recent(self) -> Sequence[dict]: ...
    def get(self,rid) -> dict: ...
