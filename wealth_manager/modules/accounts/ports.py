from typing import Protocol
from .domain import Account, Purchase

class AccountRepository(Protocol):
    def get(self, record_id: int) -> dict: ...
    def toggle_archived(self, record_id: int) -> None: ...
    def delete(self, record_id: int) -> None: ...
    def save(self, account: Account) -> int: ...

class AccountUnitOfWork(Protocol):
    accounts: AccountRepository
    def __enter__(self) -> "AccountUnitOfWork": ...
    def __exit__(self, exc_type, exc, traceback) -> None: ...
    def take_snapshot(self) -> None: ...
    def commit(self) -> None: ...
