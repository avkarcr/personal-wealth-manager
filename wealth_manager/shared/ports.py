from typing import Callable, Protocol, Sequence
from datetime import date
from wealth_manager.modules.accounts.ports import AccountRepository
from wealth_manager.modules.positions.domain import Position
from wealth_manager.modules.cashflows.domain import Cashflow
from wealth_manager.modules.rentals.domain import Lease, RentPayment
from wealth_manager.modules.valuation.domain import ExchangeRates


class PositionRepository(Protocol):
    def get(self, record_id: int) -> Position: ...
    def save(self, position: Position) -> int: ...
    def delete(self, record_id: int) -> None: ...
    def set_price(self, record_id: int, account_id: int, price: float, updated_at: str) -> None: ...


class CashflowRepository(Protocol):
    def get(self, record_id: int) -> Cashflow: ...
    def save(self, flow: Cashflow) -> int: ...
    def delete(self, record_id: int) -> None: ...
    def sync_rent(self, payment_id: int, flow) -> None: ...
    def through(self, account_id: int, day: str) -> Sequence[Cashflow]: ...


class RentalRepository(Protocol):
    def get(self, record_id: int) -> Lease: ...
    def save(self, lease: Lease) -> int: ...
    def payments(self, lease_id: int) -> Sequence[RentPayment]: ...
    def get_payment(self, record_id: int) -> RentPayment: ...
    def save_payment(self, payment: RentPayment) -> int: ...
    def delete_payment(self, record_id: int) -> None: ...
    def delete(self, record_id: int) -> None: ...


class ValuationRepository(Protocol):
    def rates(self) -> ExchangeRates: ...
    def historical_rates(self, day: str) -> ExchangeRates: ...
    def save_history(self, account_id: int, day: str, value_rub: float, invested_rub: float) -> None: ...


from wealth_manager.modules.market_data.ports import MarketPreferences, RateRepository


from wealth_manager.modules.entities.ports import EntityRepository, AssetRepository, IncomeSourceRepository

from wealth_manager.modules.planning.ports import PlanningRepository

from wealth_manager.modules.companies.ports import CompanyRepository
from wealth_manager.modules.macroeconomics.ports import ObservationRepository
from wealth_manager.modules.taxes.ports import TaxRepository

class UnitOfWork(Protocol):
    companies: CompanyRepository
    macroeconomics: ObservationRepository
    taxes: TaxRepository
    planning: PlanningRepository
    entities: EntityRepository
    assets: AssetRepository
    income_sources: IncomeSourceRepository
    market_preferences: MarketPreferences
    rates: RateRepository
    accounts: AccountRepository
    positions: PositionRepository
    cashflows: CashflowRepository
    rentals: RentalRepository
    valuations: ValuationRepository
    def __enter__(self) -> 'UnitOfWork': ...
    def __exit__(self, exc_type, exc, traceback) -> None: ...
    def take_snapshot(self) -> None: ...
    def commit(self) -> None: ...


UowFactory = Callable[[], UnitOfWork]
Clock = Callable[[], date]
