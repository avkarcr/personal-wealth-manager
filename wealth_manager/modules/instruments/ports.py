from typing import Protocol
from .domain import CryptoAsset

class Repository(Protocol):
    def save_crypto(self, record: CryptoAsset) -> int: ...
    def delete_crypto(self, record_id: int) -> None: ...
    def target(self, kind: str, record_id: int) -> dict: ...
    def link(self, holding_id: int, kind: str, record_id: int) -> None: ...
    def unlink(self, holding_id: int) -> None: ...
    def holding_link(self, holding_id: int): ...

class Reader(Protocol):
    def read(self) -> dict: ...
