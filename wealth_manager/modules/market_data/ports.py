from typing import Protocol, Optional
from .domain import Quote

class CryptoQuotes(Protocol):
    def quote(self, symbol: str, exchanges: tuple) -> Optional[Quote]: ...

class StockQuotes(Protocol):
    def price(self, ticker: str) -> Optional[float]: ...

class CentralBankRates(Protocol):
    def rates(self, day=None) -> tuple: ...

class MarketPreferences(Protocol):
    def get(self) -> dict: ...
    def profile(self,country: str) -> list: ...
    def save(self,country: str,exchanges: tuple) -> None: ...

class RateRepository(Protocol):
    def save(self, currency: str, rate: float, day: str) -> None: ...
    def save_historical(self, currency: str, rate: float, day: str) -> None: ...
    def delete(self, currency: str) -> None: ...
    def set_base(self, currency: str) -> None: ...
