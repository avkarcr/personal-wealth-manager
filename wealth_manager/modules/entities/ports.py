from typing import Protocol
from wealth_manager.modules.assets.domain import Asset
from wealth_manager.modules.income_sources.domain import IncomeSource
from wealth_manager.modules.accounts.domain import Purchase

class EntityRepository(Protocol):
    def get(self,record_id: int) -> dict: ...
    def toggle_archived(self,record_id: int) -> None: ...
    def delete(self,record_id: int) -> None: ...

class AssetRepository(Protocol):
    def get(self,record_id: int) -> dict: ...
    def save(self,asset: Asset) -> int: ...
    def set_value(self,record_id: int,value: float) -> None: ...
    def record_purchase(self,record_id: int,currency: str,purchase: Purchase) -> None: ...

class IncomeSourceRepository(Protocol):
    def get(self,record_id: int) -> dict: ...
    def save(self,source: IncomeSource) -> int: ...
